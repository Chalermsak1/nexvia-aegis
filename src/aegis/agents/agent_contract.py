"""
NEXVIA AEGIS — Agent Team Contracts & Governance Protocol.

Defines the roles, data structures, and cryptographic sign-off standards for the
AEGIS Multi-Agent Research Team operating under strict GATE_B_NOT_AUTHORIZED boundary.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum
import hashlib
import json
from typing import Any, Mapping, Sequence


class AgentRole(str, Enum):
    """Authoritative research roles within the AEGIS multi-agent team."""
    LEAD_COORDINATOR = "LEAD_COORDINATOR"
    PHYSICAL_CONTROL_AGENT = "PHYSICAL_CONTROL_AGENT"
    STATISTICAL_AUDITOR_AGENT = "STATISTICAL_AUDITOR_AGENT"
    FORENSIC_EVIDENCE_AGENT = "FORENSIC_EVIDENCE_AGENT"


class VerdictStatus(str, Enum):
    """Formal audit verdict returned by an individual agent or the whole team."""
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    APPROVED_WITH_CAVEATS = "APPROVED_WITH_CAVEATS"
    INSUFFICIENT_EVIDENCE = "INSUFFICIENT_EVIDENCE"


class TeamConsensus(str, Enum):
    """Overall team agreement state."""
    CONSENSUS_REACHED = "CONSENSUS_REACHED"
    CONSENSUS_REJECTED = "CONSENSUS_REJECTED"
    BLOCKERS_PRESENT = "BLOCKERS_PRESENT"
    GATE_B_BLOCKED = "GATE_B_BLOCKED"


@dataclass(frozen=True)
class AgentSignOff:
    """Formal cryptographic sign-off generated by an individual research agent."""
    role: AgentRole
    agent_id: str
    verdict: VerdictStatus
    findings: list[str]
    metrics: dict[str, Any]
    blockers: list[str] = field(default_factory=list)
    caveats: list[str] = field(default_factory=list)

    @property
    def signature_sha256(self) -> str:
        """Deterministically hashes the sign-off record."""
        payload = {
            "role": self.role.value,
            "agent_id": self.agent_id,
            "verdict": self.verdict.value,
            "findings": self.findings,
            "metrics": self.metrics,
            "blockers": self.blockers,
            "caveats": self.caveats,
        }
        encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
        return hashlib.sha256(encoded).hexdigest()

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["role"] = self.role.value
        data["verdict"] = self.verdict.value
        data["signature_sha256"] = self.signature_sha256
        return data


@dataclass
class TeamResearchDossier:
    """Complete consolidated research dossier compiled by the Lead Coordinator."""
    study_id: str
    title_th: str
    title_en: str
    timestamp: str
    gate_b_status: str  # Always "GATE_B_NOT_AUTHORIZED"
    consensus: TeamConsensus
    agent_signoffs: dict[str, AgentSignOff]
    key_findings_th: list[str]
    actionable_recommendations_th: list[str]
    forensic_ledger_hashes: dict[str, str] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "study_id": self.study_id,
            "title_th": self.title_th,
            "title_en": self.title_en,
            "timestamp": self.timestamp,
            "gate_b_status": self.gate_b_status,
            "consensus": self.consensus.value,
            "agent_signoffs": {k: v.to_dict() for k, v in self.agent_signoffs.items()},
            "key_findings_th": self.key_findings_th,
            "actionable_recommendations_th": self.actionable_recommendations_th,
            "forensic_ledger_hashes": self.forensic_ledger_hashes,
        }
